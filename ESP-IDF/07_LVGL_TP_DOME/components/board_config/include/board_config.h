#define BOARD_LCD_SPI_SDA GPIO_NUM_1
#define BOARD_LCD_RGB_PCLK GPIO_NUM_21
#define BOARD_LCD_RGB_HSYNC GPIO_NUM_16
#define BOARD_LCD_RGB_VSYNC GPIO_NUM_17
#define BOARD_LCD_RGB_DE GPIO_NUM_18
#define BOARD_LCD_RGB_DATA0 GPIO_NUM_15  /* B0 */
#define BOARD_LCD_RGB_DATA1 GPIO_NUM_4   /* B1 */
#define BOARD_LCD_RGB_DATA2 GPIO_NUM_5   /* B2 */
#define BOARD_LCD_RGB_DATA3 GPIO_NUM_6   /* B3 */
#define BOARD_LCD_RGB_DATA4 GPIO_NUM_7   /* B4 */
#define BOARD_LCD_RGB_DATA5 GPIO_NUM_8   /* G0 */
#define BOARD_LCD_RGB_DATA6 GPIO_NUM_47  /* G1 */
#define BOARD_LCD_RGB_DATA7 GPIO_NUM_48  /* G2 */
#define BOARD_LCD_RGB_DATA8 GPIO_NUM_46  /* G3 */
#define BOARD_LCD_RGB_DATA9 GPIO_NUM_9   /* G4 */
#define BOARD_LCD_RGB_DATA10 GPIO_NUM_10 /* G5 */
#define BOARD_LCD_RGB_DATA11 GPIO_NUM_0  /* R0 */
#define BOARD_LCD_RGB_DATA12 GPIO_NUM_11 /* R1 */
#define BOARD_LCD_RGB_DATA13 GPIO_NUM_12 /* R2 */
