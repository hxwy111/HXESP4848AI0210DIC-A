#define BOARD_LCD_BACKLIGHT_EN_ON_LEVEL 1
#define BOARD_LCD_BACKLIGHT_EN_OFF_LEVEL 0
#define BOARD_TOUCH_INT_ACTIVE_LOW 1
#define BOARD_TOUCH_I2C_ADDR_PRIMARY 0x5D
#define BOARD_TOUCH_I2C_ADDR_SECONDARY 0x14
#define BOARD_TOUCH_SDA GPIO_NUM_41
#define BOARD_TOUCH_SCL GPIO_NUM_40
#define BOARD_TOUCH_INT GPIO_NUM_45 /* TP_INT */
#define BOARD_TOUCH_RST GPIO_NUM_NC

