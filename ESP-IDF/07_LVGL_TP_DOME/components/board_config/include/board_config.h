/* HXESP4848AI0210DIC-A: ST7701S, 480x480, 3-wire SPI control + RGB565. */
#define BOARD_LCD_H_RES 480
#define BOARD_LCD_V_RES 480
#define BOARD_LCD_SPI_CS GPIO_NUM_39
